def _has_exec_name(title: str) -> bool:
    for name in EXEC_NAMES:
        if name in title:
            context = AMBIGUOUS_EXEC_NAMES.get(name)
            if context is None or any(c in title for c in context):
                return True
    return False


def _is_blocked_source(url: str, source_name: str = '') -> bool:
    """차단 도메인 또는 차단 소스 이름 여부 확인.
    Google 뉴스 RSS는 URL이 news.google.com이라 도메인 체크가 우회됨 —
    entry.source.title을 source_name으로 넘겨 추가 차단.
    """
    domain = _get_domain(url)
    if any(blocked in domain for blocked in BLOCKED_DOMAINS):
        return True
    if source_name:
        return any(blocked in source_name for blocked in BLOCKED_SOURCE_NAMES)
    return False


