def screen(title, summary=''):
    """규칙 단계. (후보인가, 엄격 기준도 통과하는가)를 돌려준다.

    후보 = 수집 범위 안이고 명백한 홍보·형식 기사가 아닌 것. 최종 판정은 AI가 한다.
    엄격 기준 = AI를 쓸 수 없을 때 대신 쓰는 보수적 기준([단독] 또는 허용어).
    """
    # 1) 범위 — 제목에 추적 대상이 있어야 한다.
    #    예외: 제목이 '금고'·금융상품어뿐이어도 요약에 추적 대상이 있으면 범위로 본다.
    title_has_kw = any(kw in title for kw in KEYWORDS)
    has_standalone_gumgo = '금고' in title and '새마을' not in title
    has_product_hint = any(p in title for p in CLICKBAIT_PRODUCT_HINTS)
    summary_fallback = (not title_has_kw) and (has_standalone_gumgo or has_product_hint) \
        and any(kw in summary for kw in KEYWORDS)
    if not title_has_kw and not summary_fallback and not _has_exec_name(title):
        return False, False

    # 2) 명백한 형식·홍보 기사
    if _is_photo_caption(title):
        return False, False
    if any(p in title for p in STRUCTURAL_PROMO_PATTERNS) or any(p in title for p in PROMO_KEYWORDS) \
            or any(r.search(title) for r in PROMO_REGEXES):
        return False, False

    # 3) 농협·수협의 농촌·어촌·재해 활동 (금융 실체 단어가 함께 있으면 남긴다)
    if (any(t in title for t in PRIMARY_INDUSTRY_TOPICS) or _PRIMARY_RE.search(title)) \
            and not any(t in title for t in FINANCIAL_SUBSTANCE_TERMS):
        return False, False

    # 여기까지 오면 후보. 아래는 AI를 못 쓸 때의 엄격 기준.
    if '[단독]' in title or '[단독보도]' in title:
        return True, True
    probe = title
    for noise in _WHITELIST_NOISE:
        probe = probe.replace(noise, ' ')
    if any(kw in probe for kw in WHITELIST_KEYWORDS):
        return True, True
    if summary_fallback and (any(kw in summary for kw in WHITELIST_KEYWORDS)
                             or sum(1 for kw in KEYWORDS if kw in summary) >= 2):
        return True, True
    return True, False


def is_relevant(title, summary=''):
    """AI 없이 규칙만으로 본 통과 여부 (엄격 기준). 점검 스크립트 호환용."""
    return screen(title, summary)[1]


STALE_BREAKING_SEC = 3 * 3600


def _published_ts(published: str):
    """발행 시각 문자열(네이버 'YYYY-MM-DD HH:MM KST' 또는 RSS RFC 822) → epoch 초. 모르면 None."""
    if not published:
        return None
    try:
        if published.endswith('KST'):
            kst = timezone(timedelta(hours=9))
            return datetime.strptime(published, '%Y-%m-%d %H:%M KST').replace(tzinfo=kst).timestamp()
        from email.utils import parsedate_to_datetime
        dt = parsedate_to_datetime(published)
        if dt.tzinfo is None:   # '-0000' 표기는 시간대 없는 값으로 읽힌다 — UTC로 본다
            dt = dt.replace(tzinfo=timezone.utc)
        return dt.timestamp()
    except Exception:
        return None


def _consider(candidates: list, seen: set, seen_titles: list,
              title: str, url: str, summary: str, source: str, published: str) -> None:
    """기사 한 건을 규칙 단계에 태워, 남으면 AI 판정 대기열에 넣는다."""
    title = html.unescape(title).strip()
    if not title or not url:
        return
    # 몇 시간 지나 들어온 [속보]는 이미 정리 기사로 대체됐다 (11-22 오전 9시대 속보가 저녁 6시에 나간 사례)
    if '[속보]' in title:
        ts = _published_ts(published)
        if ts is not None and time.time() - ts > STALE_BREAKING_SEC:
            return
    if _is_blocked_source(url, source):
        return
    is_candidate, strict_ok = screen(title, summary)
    if not is_candidate:
        return
    if get_article_id(url, title) in seen:
        return
    if _is_similar_title(title, seen_titles):
        return
    candidates.append({'title': title, 'url': url, 'summary': summary, 'published': published,
                       'source': source, 'strict_ok': strict_ok})


def _select(candidates: list, seen: set, seen_titles: list) -> list:
    """AI 판정을 거쳐 보낼 기사를 고르고, 같은 뉴스는 하나만 남긴다.

    AI가 판정하지 못한 기사는 엄격 기준을, AI가 중복 여부를 판정하지 못한 기사는 규칙 중복 판정을 따른다.
    """
    verdicts = _llm_judge(candidates)
    passing = []
    for c in candidates:
        send = verdicts.get(c['title'].strip())
        if send is None:
            send = c['strict_ok']
        if send:
            passing.append(c)

    now = time.time()
    recent = [t for t, ts in seen_titles if now - ts < 24 * 3600]
    dup_flags = _llm_dedup(passing, recent)

    picked = []
    for c, dup in zip(passing, dup_flags):
        exact = any(_normalize_title(t) == _normalize_title(c['title']) for t, _ in seen_titles)
        if dup is None:
            dup = _is_similar_title(c['title'], seen_titles)
        if dup or exact:
            logger.info(f"중복 제외: {c['title'][:60]}")
            continue
        seen.add(get_article_id(c['url'], c['title']))
        seen_titles.append([c['title'], time.time()])
        picked.append({k: c[k] for k in ('title', 'url', 'summary', 'published', 'source')})
    return picked


def _strip_html(text: str) -> str:
    """네이버 API 응답의 간단한 HTML 태그 제거"""
    return re.sub(r'<[^>]+>', '', text).strip()


def fetch_from_naver(candidates: list, seen: set, seen_titles: list, cutoff: datetime) -> None:
    """네이버 뉴스 검색 API로 기사를 수집해 판정 대기열(candidates)에 넣는다.

    NAVER_CLIENT_ID / NAVER_CLIENT_SECRET 환경변수가 없으면 조용히 건너뜀.
    RSS로 커버되지 않는 언론사(MTN 등)의 기사를 보완하는 용도.
    """
    if not NAVER_CLIENT_ID or not NAVER_CLIENT_SECRET:
        logger.debug("네이버 API 키 미설정 — 건너뜀")
        return

    headers = {
        'X-Naver-Client-Id': NAVER_CLIENT_ID,
        'X-Naver-Client-Secret': NAVER_CLIENT_SECRET,
    }

    for query in NAVER_SEARCH_QUERIES:
        try:
            params = {
                'query': query,
                'display': 100,  # 회당 최대 수집 건수 (API 상한)
                'sort': 'date',  # 최신순
            }
            resp = requests.get(NAVER_API_URL, headers=headers, params=params, timeout=10)
            resp.raise_for_status()
            items = resp.json().get('items', [])
            NAVER_STATE.update(ok=True, error='')

            for item in items:
                title = _strip_html(item.get('title', ''))
                url = item.get('originallink') or item.get('link', '')
                summary = _strip_html(item.get('description', ''))
                pub_date_str = item.get('pubDate', '')  # RFC 822 형식

                # 발행일 파싱 및 24시간 필터
                if pub_date_str:
                    try:
                        from email.utils import parsedate_to_datetime
                        pub_dt = parsedate_to_datetime(pub_date_str).astimezone(timezone.utc)
                        if pub_dt < cutoff:
                            continue
                        published = pub_dt.strftime('%Y-%m-%d %H:%M KST')
                    except Exception:
                        published = pub_date_str
                else:
                    published = ''

                source = item.get('link', '').split('/')[2] if item.get('link') else ''
                _consider(candidates, seen, seen_titles, title, url, summary, source, published)

        except requests.exceptions.RequestException as e:
            logger.error(f"네이버 API 수집 오류 [query={query}]: {e}")
            NAVER_STATE.update(ok=False, error=f"{type(e).__name__}: {str(e)[:150]}")
            break  # 같은 오류로 남은 검색어를 계속 두드리지 않는다


def fetch_new_articles():
    seen = load_seen()
    seen_titles = load_seen_titles()
    candidates = []
    cutoff = datetime.now(timezone.utc) - timedelta(hours=24)

    # ── 1. RSS 피드 수집 ─────────────────────────────────────────
    for feed_url in _feed_urls():
        try:
            feed = feedparser.parse(feed_url)
            for entry in feed.entries:
                title = entry.get('title', '').strip()
                url = entry.get('link', '').strip()
                summary = entry.get('summary', '').strip()
                published = entry.get('published', '')

                # 24시간 이상 된 기사 제외
                published_parsed = entry.get('published_parsed')
                if published_parsed:
                    pub_dt = datetime(*published_parsed[:6], tzinfo=timezone.utc)
                    if pub_dt < cutoff:
                        continue
                else:
                    # published_parsed 없으면 published 문자열로 직접 파싱 시도
                    published_str = entry.get('published', '')
                    if published_str:
                        try:
                            from email.utils import parsedate_to_datetime
                            pub_dt = parsedate_to_datetime(published_str).astimezone(timezone.utc)
                            if pub_dt < cutoff:
                                continue
                        except Exception:
                            pass  # 파싱 실패 시 통과 허용

                # source: Google 뉴스는 entry.source.title, 언론사 직접 피드는 feed.feed.title
                source = ''
                if hasattr(entry, 'source') and hasattr(entry.source, 'title'):
                    source = entry.source.title
                elif hasattr(feed, 'feed') and hasattr(feed.feed, 'title'):
                    source = feed.feed.title

                _consider(candidates, seen, seen_titles, title, url, summary, source, published)

        except Exception as e:
            logger.error(f"피드 수집 오류 [{feed_url}]: {e}")

    # ── 2. 네이버 뉴스 검색 API 수집 (RSS 미커버 언론사 보완) ──────
    fetch_from_naver(candidates, seen, seen_titles, cutoff)

    # ── 3. AI 판정 → 중복 제거 ───────────────────────────────────
    new_articles = _select(candidates, seen, seen_titles)

    if new_articles:
        save_seen(seen)
        save_seen_titles(seen_titles)

    logger.info(f"후보 {len(candidates)}건 → 발송 {len(new_articles)}건 (AI 판정 상태: {LLM_STATE['ok']})")
    return new_articles


def _to_kst_str(published: str) -> str:
    """발행 시각을 'M월 D일 오전/오후 H:MM' 형식(KST)으로 변환"""
    if not published:
        return ''
    try:
        from zoneinfo import ZoneInfo
        KST = ZoneInfo('Asia/Seoul')
        # 네이버 API 형식: "2026-04-05 20:02 KST"
        if published.endswith('KST'):
            dt = datetime.strptime(published, '%Y-%m-%d %H:%M KST').replace(tzinfo=KST)
        else:
            # RSS RFC 822 형식: "Sun, 05 Apr 2026 22:00:00 GMT"
            from email.utils import parsedate_to_datetime
            dt = parsedate_to_datetime(published).astimezone(KST)
        h, m = dt.hour, dt.minute
        ampm = '오전' if h < 12 else '오후'
        h12 = h % 12 or 12
        return f"{dt.month}월 {dt.day}일 {ampm} {h12}:{m:02d}"
    except Exception:
        return published


def _extract_media(title: str, source: str, url: str) -> tuple[str, str]:
    """제목 뒤의 ' - 매체명' / ' | 매체명' 분리 + source/url로 보완.
    Returns (clean_title, media_name)
    """
    clean_title = title
    media = ''
    # 제목 뒤 ' - 매체명' 또는 ' | 매체명' 패턴 제거
    m = re.search(r'\s+[\-\|]\s+([^\-\|]{1,30})$', title)
    if m:
        media = m.group(1).strip()
        clean_title = title[:m.start()].strip()
    # source가 명시돼 있으면 우선 사용 (Google RSS entry.source.title 등)
    if source:
        clean_source = source.split(' > ')[0].split(' - ')[0].strip()
        if clean_source:
            media = clean_source
    # 그래도 비어있으면 URL 도메인 fallback
    if not media:
        try:
            domain = urlparse(url).netloc
            for prefix in ('www.', 'news.', 'biz.', 'm.'):
                if domain.startswith(prefix):
                    domain = domain[len(prefix):]
                    break
            media = domain
        except Exception:
            media = ''
    return clean_title, media


def format_article(article):
    title = article['title']
    url = article['url']
    published = article.get('published', '')
    source = article.get('source', '')

    clean_title, media = _extract_media(title, source, url)
    time_str = _to_kst_str(published)

    lines = [f"<b>{clean_title}</b>"]
    if time_str:
        lines.append(time_str)
    if media:
        lines.append(media)
    lines.append(f'<a href="{url}">링크</a>')

    return '\n'.join(lines)
